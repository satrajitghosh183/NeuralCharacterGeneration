TriMesh marching_cubes(const std::vector<float>& field, int gx, int gy, int gz, float iso,
                       std::array<float, 3> origin, std::array<float, 3> spacing) {
  NCG_CHECK(static_cast<int64_t>(field.size()) == static_cast<int64_t>(gx) * gy * gz,
            "marching_cubes: field size mismatch");

  auto at_field = [&](int x, int y, int z) -> float {
    return field[(static_cast<int64_t>(z) * gy + y) * gx + x];
  };
  auto world = [&](int x, int y, int z, std::array<float, 3>& out) {
    out[0] = origin[0] + static_cast<float>(x) * spacing[0];
    out[1] = origin[1] + static_cast<float>(y) * spacing[1];
    out[2] = origin[2] + static_cast<float>(z) * spacing[2];
  };

  std::vector<float> verts;   // flat xyz
  std::vector<int64_t> faces;  // flat triples

  for (int z = 0; z < gz - 1; ++z) {
    for (int y = 0; y < gy - 1; ++y) {
      for (int x = 0; x < gx - 1; ++x) {
        float val[8];
        std::array<float, 3> pos[8];
        int cube_index = 0;
        for (int i = 0; i < 8; ++i) {
          const int cx = x + kCorner[i][0];
          const int cy = y + kCorner[i][1];
          const int cz = z + kCorner[i][2];
          val[i] = at_field(cx, cy, cz);
          world(cx, cy, cz, pos[i]);
          if (val[i] < iso) cube_index |= (1 << i);
        }
        const int edges = kEdgeTable[cube_index];
        if (edges == 0) continue;

        std::array<float, 3> vlist[12];
        for (int e = 0; e < 12; ++e) {
          if ((edges & (1 << e)) == 0) continue;
          const int a = kEdgeCorners[e][0];
          const int b = kEdgeCorners[e][1];
          float t = 0.5F;
          const float denom = val[b] - val[a];
          if (denom != 0.0F) t = (iso - val[a]) / denom;
          for (int k = 0; k < 3; ++k) vlist[e][k] = pos[a][k] + t * (pos[b][k] - pos[a][k]);
        }

        for (int i = 0; kTriTable[cube_index][i] != -1; i += 3) {
          const int64_t base = static_cast<int64_t>(verts.size()) / 3;
          for (int j = 0; j < 3; ++j) {
            const auto& v = vlist[kTriTable[cube_index][i + j]];
            verts.push_back(v[0]);
            verts.push_back(v[1]);
            verts.push_back(v[2]);
          }
          faces.push_back(base + 0);
          faces.push_back(base + 1);
          faces.push_back(base + 2);
        }
      }
    }
  }

  TriMesh mesh;
  const int64_t nv = static_cast<int64_t>(verts.size()) / 3;
  const int64_t nf = static_cast<int64_t>(faces.size()) / 3;
  mesh.vertices = torch::from_blob(verts.data(), {nv, 3}, torch::kFloat).clone();
  mesh.faces = torch::from_blob(faces.data(), {nf, 3}, torch::kLong).clone();
  return mesh;
}

